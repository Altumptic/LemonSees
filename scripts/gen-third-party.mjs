// Перелік сторонніх ліцензій.
//   node scripts/gen-third-party.mjs            → перезаписує THIRD-PARTY-LICENSES.md (таблиця, комітиться)
//   node scripts/gen-third-party.mjs --check    → падає, якщо файл застарів (CI)
//   node scripts/gen-third-party.mjs --full [--out dist/THIRD-PARTY-LICENSES.txt]
//                                               → повні тексти ліцензій для збірок (потрібні node_modules і cargo)
// Джерела: package-lock.json (лише production-залежності) і `cargo metadata` (крейти ядра).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_MD = join(root, "THIRD-PARTY-LICENSES.md");
const args = process.argv.slice(2);
const check = args.includes("--check");
const full = args.includes("--full");
const outIdx = args.indexOf("--out");
const outTxt = resolve(root, outIdx >= 0 ? args[outIdx + 1] : "dist/THIRD-PARTY-LICENSES.txt");

// Ці пакети оголошують ліцензію застарілим масивом `licenses`, якого немає в package-lock. Усі три — MIT
// (звірено з метаданими реєстру npm).
const NPM_OVERRIDES = { ssh2: "MIT", buildcheck: "MIT", "cpu-features": "MIT" };

/* ---------- npm ---------- */
function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  const seen = new Map();
  for (const [key, v] of Object.entries(lock.packages)) {
    if (!key || v.dev) continue;
    const name = key.split("node_modules/").pop();
    const license = v.license ?? NPM_OVERRIDES[name] ?? "UNKNOWN";
    const id = `${name}@${v.version}`;
    if (!seen.has(id)) seen.set(id, { name, version: v.version, license, optional: !!v.optional, dir: join(root, key) });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

/* ---------- Rust ---------- */
function rustCrates() {
  const out = execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: join(root, "core"), encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell: process.platform === "win32" });
  return JSON.parse(out)
    .packages.filter((p) => p.source) // без крейтів самого воркспейсу
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "UNKNOWN", dir: dirname(p.manifest_path) }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

const count = (list) => {
  const m = {};
  for (const p of list) m[p.license] = (m[p.license] ?? 0) + 1;
  return Object.entries(m).sort((a, b) => b[1] - a[1]);
};

function renderMd(npm, rust) {
  const row = (p, extra = "") => `| ${p.name} | ${p.version} | ${p.license}${extra} |`;
  const summary = (l) => count(l).map(([k, n]) => `${k} × ${n}`).join(" · ");
  return `# Third-party licenses

LemonSees is released under the [MIT License](LICENSE). It bundles the third-party software listed below, each under its
own licence. **No dependency in the production tree is under a copyleft licence** (GPL, LGPL, AGPL, MPL or similar).

This file is generated by \`npm run legal\` from \`package-lock.json\` (production dependencies only) and \`cargo metadata\`.
CI fails if it is out of date. Release builds ship the **full licence texts** in \`THIRD-PARTY-LICENSES.txt\`
(inside the installers and the web bundle).

## Summary

- npm packages (${npm.length}): ${summary(npm)}
- Rust crates (${rust.length}): ${summary(rust)}

## Notes

- **Fonts.** DM Sans, JetBrains Mono and Source Serif 4 are bundled through the \`@fontsource-variable/*\` packages under the
  SIL Open Font License 1.1. Their copyright notices and the licence text are in each package's \`LICENSE\` file, which is
  included in the full texts. The fonts are used unmodified.
- **Unicode data.** The \`regex-syntax\` crate (a dependency of the Rust core) contains Unicode data under the Unicode-3.0
  licence; it is included in the full texts.
- **Electron and Chromium.** Desktop builds include Electron's own notices (\`LICENSE.electron.txt\` and
  \`LICENSES.chromium.html\`) next to the executable.
- **Optional native modules.** \`buildcheck\` and \`cpu-features\` are optional dependencies of \`ssh2\`. They are excluded from
  the packaged desktop builds and are listed here because they appear in the production dependency tree.
- **\`ssh2\`, \`buildcheck\`, \`cpu-features\`** declare their licence with the legacy \`licenses\` array, which \`package-lock.json\`
  does not carry. All three are MIT according to the npm registry; this is recorded in \`scripts/gen-third-party.mjs\`.
- Some Rust crates in the list apply only to other platforms; the list follows \`Cargo.lock\`.

## npm packages

| Package | Version | License |
|---|---|---|
${npm.map((p) => row(p, p.optional ? " (optional)" : "")).join("\n")}

## Rust crates

| Crate | Version | License |
|---|---|---|
${rust.map((p) => row(p)).join("\n")}
`;
}

/* ---------- повні тексти ---------- */
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)(\.|-|$)/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f) && statSync(join(dir, f)).isFile())
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), "utf8").slice(0, 120_000) }));
}

/** Для пакета без файлу ліцензії: лише перевірні факти з його package.json (текст ліцензії не вигадуємо). */
function declared(p) {
  let meta = {};
  try {
    meta = JSON.parse(readFileSync(join(p.dir, "package.json"), "utf8"));
  } catch {
    /* пакета немає на диску */
  }
  const author = typeof meta.author === "string" ? meta.author : meta.author?.name;
  const repo = typeof meta.repository === "string" ? meta.repository : meta.repository?.url;
  const lines = [`Declared licence: ${p.license} (terms: https://spdx.org/licenses/${encodeURIComponent(p.license)}.html)`];
  if (author) lines.push(`Author (package.json): ${author}`);
  if (repo) lines.push(`Repository: ${repo}`);
  return lines.join("\n") + "\n";
}

function renderFull(npm, rust, rustAvailable) {
  const parts = [`LemonSees third-party licence texts\nGenerated by scripts/gen-third-party.mjs. The list with SPDX identifiers is in THIRD-PARTY-LICENSES.md.\n`];
  const section = (title, list) => {
    parts.push(`\n${"=".repeat(78)}\n${title}\n${"=".repeat(78)}\n`);
    for (const p of list) {
      parts.push(`\n--- ${p.name} ${p.version} (${p.license}) ---\n`);
      const texts = licenseTexts(p.dir);
      if (!texts.length) parts.push(`(no licence file is shipped with this package)\n${declared(p)}`);
      for (const t of texts) parts.push(`[${t.file}]\n${t.text.trim()}\n`);
    }
  };
  section("npm packages", npm);
  if (rustAvailable) section("Rust crates", rust);
  else parts.push("\n(Rust crate licences were not included: cargo was not available when this file was generated.)\n");
  return parts.join("");
}

/* ---------- main ---------- */
const npm = npmPackages();
let rust = [];
let rustAvailable = true;
try {
  rust = rustCrates();
} catch (e) {
  rustAvailable = false;
  if (!full) {
    console.error("[third-party] cargo is required to generate the Rust section:", e.message.split("\n")[0]);
    process.exit(1);
  }
  console.warn("[third-party] cargo unavailable: the full text will not include Rust crates");
}

// Політика: у production-дереві немає невідомих чи копілефтних ліцензій. Інакше цей файл не може так стверджувати.
const FORBIDDEN = /GPL|MPL|EPL|CDDL|SSPL|CC-BY-SA|UNKNOWN/i;
const offending = [...npm, ...rust].filter((p) => FORBIDDEN.test(p.license));
if (offending.length) {
  console.error("[third-party] licence policy violated (unknown or copyleft):");
  for (const p of offending) console.error(`  ${p.name}@${p.version}: ${p.license}`);
  process.exit(1);
}

if (full) {
  mkdirSync(dirname(outTxt), { recursive: true });
  const text = renderFull(npm, rust, rustAvailable);
  writeFileSync(outTxt, text);
  const missing = npm.filter((p) => !licenseTexts(p.dir).length).length;
  console.log(`[third-party] wrote ${outTxt} (${(text.length / 1024).toFixed(0)} KiB), ${npm.length} npm + ${rust.length} Rust; ${missing} npm package(s) without a licence file`);
} else {
  const md = renderMd(npm, rust);
  if (check) {
    const cur = existsSync(OUT_MD) ? readFileSync(OUT_MD, "utf8") : "";
    if (cur !== md) {
      console.error("THIRD-PARTY-LICENSES.md is stale: run `npm run legal` and commit the result");
      process.exit(1);
    }
    console.log("THIRD-PARTY-LICENSES.md is up to date");
  } else {
    writeFileSync(OUT_MD, md);
    console.log(`[third-party] wrote THIRD-PARTY-LICENSES.md (${npm.length} npm, ${rust.length} Rust)`);
  }
}
