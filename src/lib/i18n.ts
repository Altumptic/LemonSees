const DICTS: Partial<Record<Lang, Record<string, string>>> = { en: EN, ru: RU, pl: PL, zh: ZH };

// Одна стабільна функція перекладу на мову — без нових замикань на кожен рендер
const T_CACHE = new Map<Lang, (s: string) => string>();
function translator(lang: Lang) {
  let t = T_CACHE.get(lang);
  if (!t) {
    const d = DICTS[lang];
    t = lang === "uk" ? (s: string) => s : (s: string) => d?.[s] ?? EN[s] ?? s;
    T_CACHE.set(lang, t);
  }
  return t;
}

export function useI18n() {
  const { settings } = useSettings();
  return { t: translator(settings.lang), lang: settings.lang };
}
